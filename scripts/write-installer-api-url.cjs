const fs = require("node:fs");
const path = require("node:path");

const DEFAULT_INSTALLER_API_URL = "http://localhost:3960";
const INSTALLER_API_URL_ENV_VAR = "ACTION_DESK_INSTALLER_API_URL";
const INSTALLER_AZURE_CLIENT_ID_ENV_VAR = "ACTION_DESK_INSTALLER_AZURE_CLIENT_ID";
const INSTALLER_AZURE_TENANT_ID_ENV_VAR = "ACTION_DESK_INSTALLER_AZURE_TENANT_ID";
const GENERATED_DEFINE_PATH = path.resolve(
  __dirname,
  "..",
  "build",
  "installer-api-url.generated.nsh",
);

function readRequiredInstallerValue(envVarName, value = process.env[envVarName]) {
  const normalized = String(value || "").trim();

  if (!normalized) {
    throw new Error(
      `${envVarName} is required to build the Windows installer. ` +
      `Set ${envVarName} before running npm run package:win.`,
    );
  }

  return normalized;
}

function normalizeInstallerApiUrl(value = process.env[INSTALLER_API_URL_ENV_VAR]) {
  const candidate = readRequiredInstallerValue(
    INSTALLER_API_URL_ENV_VAR,
    value,
  ).replace(/\/+$/, "");

  if (!candidate) {
    throw new Error(`${INSTALLER_API_URL_ENV_VAR} must not be empty.`);
  }

  let parsedUrl;

  try {
    parsedUrl = new URL(candidate);
  } catch {
    throw new Error(`${INSTALLER_API_URL_ENV_VAR} must be a valid absolute URL.`);
  }

  if (parsedUrl.protocol !== "http:" && parsedUrl.protocol !== "https:") {
    throw new Error(`${INSTALLER_API_URL_ENV_VAR} must use http or https.`);
  }

  return parsedUrl.origin;
}

function normalizeInstallerAzureValue(envVarName, value = process.env[envVarName]) {
  return readRequiredInstallerValue(envVarName, value);
}

function escapeNsisDefineValue(value) {
  return String(value)
    .replace(/\$/g, "$$$$")
    .replace(/"/g, '$\\"');
}

function formatInstallerApiUrlDefine(config) {
  return [
    "; Generated by scripts/write-installer-api-url.cjs. Do not edit by hand.",
    `!define ACTION_DESK_INSTALLER_API_URL "${escapeNsisDefineValue(config.apiUrl)}"`,
    `!define ACTION_DESK_INSTALLER_AZURE_CLIENT_ID "${escapeNsisDefineValue(config.azureClientId)}"`,
    `!define ACTION_DESK_INSTALLER_AZURE_TENANT_ID "${escapeNsisDefineValue(config.azureTenantId)}"`,
    "",
  ].join("\r\n");
}

function writeInstallerApiUrlDefine(options = {}) {
  const outputPath = options.outputPath ?? GENERATED_DEFINE_PATH;
  const apiUrl = normalizeInstallerApiUrl(options.apiUrl);
  const azureClientId = normalizeInstallerAzureValue(
    INSTALLER_AZURE_CLIENT_ID_ENV_VAR,
    options.azureClientId,
  );
  const azureTenantId = normalizeInstallerAzureValue(
    INSTALLER_AZURE_TENANT_ID_ENV_VAR,
    options.azureTenantId,
  );
  const config = {
    apiUrl,
    azureClientId,
    azureTenantId,
  };

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, formatInstallerApiUrlDefine(config), "utf8");

  return {
    ...config,
    apiUrl,
    outputPath,
  };
}

if (require.main === module) {
  const result = writeInstallerApiUrlDefine();

  console.log(
    `[Action Desk] Installer runtime config API URL: ${result.apiUrl}`,
  );
  console.log("[Action Desk] Installer Azure client ID: configured");
  console.log("[Action Desk] Installer Azure tenant ID: configured");
  console.log(
    `[Action Desk] Wrote NSIS API URL define: ${result.outputPath}`,
  );
}

module.exports = {
  DEFAULT_INSTALLER_API_URL,
  GENERATED_DEFINE_PATH,
  INSTALLER_AZURE_CLIENT_ID_ENV_VAR,
  INSTALLER_AZURE_TENANT_ID_ENV_VAR,
  INSTALLER_API_URL_ENV_VAR,
  escapeNsisDefineValue,
  formatInstallerApiUrlDefine,
  normalizeInstallerAzureValue,
  normalizeInstallerApiUrl,
  readRequiredInstallerValue,
  writeInstallerApiUrlDefine,
};
